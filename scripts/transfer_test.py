"""Zero-shot transfer to another continent: train on US basins only, forecast Central European basins.

    python scripts/transfer_test.py --transfer data/transfer_lamah --name transfer_lamah

Every model is fitted on data/caravan/train.parquet (US only), exactly as for the US test set, then predicts the
transfer package. The transfer basins' data are never used for fitting; their past flow and thresholds are inputs
at prediction time, as for the US held-out basins. Writes outputs/<name>/ and docs/TRANSFER_EUROPE.md.
"""
from __future__ import annotations

import argparse
import importlib
import json
import sys
import time
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src import evaluate, submission  # noqa: E402

ID, DATE = "gauge_id", "date"
MODELS = [("src.bs_models:RobustMeanModel", "BasinPulse (final)"),
          ("src.baselines:Climatology", "Climatology"),
          ("src.baselines", "Persistence")]


def load(spec):
    mod, _, cls = spec.partition(":")
    m = importlib.import_module(mod)
    if cls:
        o = getattr(m, cls)()
        return o.fit, o.predict
    return m.fit, m.predict


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data", type=Path, default=ROOT / "data" / "caravan")
    ap.add_argument("--transfer", type=Path, default=ROOT / "data" / "transfer_lamah")
    ap.add_argument("--name", default="transfer_lamah")
    ap.add_argument("--n-boot", type=int, default=100)
    a = ap.parse_args()
    out = ROOT / "outputs" / a.name
    out.mkdir(parents=True, exist_ok=True)

    train = pd.read_parquet(a.data / "train.parquet")
    us_static = pd.read_parquet(a.data / "static.parquet")
    us_thr = pd.read_csv(a.data / "thresholds.csv", dtype={ID: str})
    test = pd.read_parquet(a.transfer / "test.parquet")
    hist = pd.read_parquet(a.transfer / "history.parquet")
    st = pd.read_parquet(a.transfer / "static.parquet")
    thr = pd.read_csv(a.transfer / "thresholds.csv", dtype={ID: str})
    # attributes and thresholds of both continents (the fitted model only ever sees US training rows)
    static_all = pd.concat([us_static, st], ignore_index=True)
    thr_all = pd.concat([us_thr, thr], ignore_index=True)

    all_m = []
    for spec, label in MODELS:
        t0 = time.time()
        fit, predict = load(spec)
        model = fit(train, us_static, us_thr)
        p = predict(model, test, hist, static_all, thr_all)
        p[ID] = p[ID].astype(str)
        submission.assert_valid(p, test[[ID, DATE]])
        tag = spec.replace(":", "_").replace(".", "_")
        p.to_parquet(out / f"predictions_{tag}.parquet", index=False)
        labels = pd.read_parquet(a.transfer / "test_labels.parquet")
        m, rel = evaluate.score(p, labels, thr, n_boot=a.n_boot)
        m["model"] = label
        all_m.append(m)
        pd.concat([r.assign(slice=k) for k, r in rel.items()]).to_csv(out / f"reliability_{tag}.csv", index=False)
        print(f"{label}: {time.time() - t0:.0f} s", flush=True)
    M = pd.concat(all_m, ignore_index=True)
    M.to_csv(out / "metrics.csv", index=False)

    show = [("nse_median", "NSE (median)"), ("kge_median", "KGE (median)"), ("mae_pooled", "MAE (mm/day)"),
            ("auprc_high", "High-flow AUPRC"), ("auprc_extreme", "Extreme-flow AUPRC"),
            ("brier_skill_high", "Brier skill (high)"), ("precision_at_budget20_high", "Precision @ 20 alerts/yr"),
            ("recall_at_budget20_high", "Recall @ 20 alerts/yr"),
            ("interval_coverage", "Range coverage (target 0.80)"), ("interval_width", "Range width (mm/day)")]
    nb = int(M.n_basins.iloc[0])
    lines = ["# Zero-shot transfer to Central Europe", "",
             f"Models fitted on **239 US basins only** (CAMELS-US, 1981–2008), then applied without any retraining "
             f"to **{nb} Central European basins** (LaMAH-CE: Austria, Germany, Switzerland), test period 2008-10 to "
             "2014-09. Same inputs, attribute recipe and event definition (95th / 99th percentile of 1981–2008 flow). "
             "95% CIs resample basins. Generated by `scripts/transfer_test.py`.", ""]
    for h in (1, 3, 7):
        lines += [f"## {h}-day horizon", "", "| metric | " + " | ".join(lbl for _, lbl in MODELS) + " |",
                  "|---" * (1 + len(MODELS)) + "|"]
        for k, lab in show:
            cells = []
            for _, lbl in MODELS:
                r = M[(M.model == lbl) & (M.horizon == h) & (M.metric == k)]
                if len(r):
                    r = r.iloc[0]
                    ci = "" if pd.isna(r.ci_low) else f" [{r.ci_low:.2f}, {r.ci_high:.2f}]"
                    cells.append(f"{r.value:.3f}{ci}")
                else:
                    cells.append("")
            lines.append(f"| {lab} | " + " | ".join(cells) + " |")
        ev = M[(M.model == MODELS[0][1]) & (M.horizon == h) & (M.metric == "auprc_high")].n_events.iloc[0]
        lines += ["", f"High-flow days: {int(ev):,}", ""]
    lines += ["Data: LaMAH-CE (Klingler et al. 2021, CC-BY-SA-4.0) via Caravan v1.6; used for evaluation only.", ""]
    (ROOT / "docs" / "TRANSFER_EUROPE.md").write_text("\n".join(lines), encoding="utf-8")
    (out / "run.json").write_text(json.dumps({"models": [m for m, _ in MODELS], "n_basins": nb}), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()

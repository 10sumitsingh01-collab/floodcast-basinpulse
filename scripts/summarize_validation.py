"""Summarise every validation experiment into docs/EXPERIMENTS.md (training data only; no test labels).

    python scripts/summarize_validation.py

Reads outputs/<run>/validation_metrics.csv and validation_stress.csv produced by
`basinshift_run.py --validate`. All model choices in this project were made from these tables.
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

OUT = Path("outputs")
RUNS = [  # (run dir, label, what it tests)
    ("val_persistence", "Persistence", "reference: tomorrow = today, calibrated range and probabilities"),
    ("val_lgbm_v1", "LightGBM v1 (median)", "quantile LightGBM, median as forecast"),
    ("val_lgbm_v2_mean", "LightGBM v2 (mean)", "v1 + mean forecast with Duan smearing"),
    ("val_h1_nostatic", "H1: no catchment attributes", "v1 without the 28 static attributes"),
    ("val_noflow", "No flow history (ungauged)", "v1 without any observed-flow input"),
    ("val_robust_h4", "H4: robustness training", "v1 trained with 15% of inputs hidden"),
    ("val_robust_mean", "Final: H4 + mean", "robustness training + mean forecast"),
]
METRICS = [("nse_median", "NSE"), ("kge_median", "KGE"), ("mae_pooled", "MAE"), ("auprc_high", "AUPRC high"),
           ("auprc_extreme", "AUPRC extreme"), ("brier_skill_high", "Brier skill"),
           ("interval_coverage", "coverage"), ("interval_width", "width")]


def table(test_set: str) -> list[str]:
    head = "| model | " + " | ".join(f"{lab} {h}d" for _, lab in METRICS[:6] for h in (1, 3, 7)) + " |"
    lines = [head, "|---" * (1 + 6 * 3) + "|"]
    for run, label, _ in RUNS:
        f = OUT / run / "validation_metrics.csv"
        if not f.exists():
            continue
        m = pd.read_csv(f)
        m = m[m.test_set == test_set].set_index(["metric", "horizon"])["value"]
        cells = [f"{m.get((k, h), float('nan')):.3f}" for k, _ in METRICS[:6] for h in (1, 3, 7)]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    return lines


def interval_table(test_set: str) -> list[str]:
    lines = ["| model | coverage 1d | 3d | 7d | width 1d | 3d | 7d |", "|---|---|---|---|---|---|---|"]
    for run, label, _ in RUNS:
        f = OUT / run / "validation_metrics.csv"
        if not f.exists():
            continue
        m = pd.read_csv(f)
        m = m[m.test_set == test_set].set_index(["metric", "horizon"])["value"]
        cells = [f"{m.get((k, h)):.3f}" for k in ("interval_coverage", "interval_width") for h in (1, 3, 7)]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    return lines


def stress_table() -> list[str]:
    a, b = OUT / "val_v1_stress" / "validation_stress.csv", OUT / "val_robust_h4" / "validation_stress.csv"
    if not (a.exists() and b.exists()):
        return ["(stress runs missing)"]
    a, b = pd.read_csv(a), pd.read_csv(b)
    lines = ["| scenario | NSE 1d: v1 | NSE 1d: H4 | AUPRC high 1d: v1 | AUPRC high 1d: H4 |", "|---|---|---|---|---|"]
    for sc in a.scenario.unique():
        g = lambda d, k: d[(d.scenario == sc) & (d.horizon == 1) & (d.metric == k)].stressed.iloc[0]  # noqa: E731
        lines.append(f"| {sc} | {g(a, 'nse_median'):.3f} | {g(b, 'nse_median'):.3f} | "
                     f"{g(a, 'auprc_high'):.3f} | {g(b, 'auprc_high'):.3f} |")
    for h in (1, 3, 7):
        x = a[(a.horizon == h) & (a.metric == "nse_median")].stressed.mean()
        y = b[(b.horizon == h) & (b.metric == "nse_median")].stressed.mean()
        lines.append(f"| **mean, {h}-day NSE** | {x:.3f} | {y:.3f} | | |")
    return lines


def main() -> None:
    lines = ["# Validation experiments (training data only)", "",
             "Every model choice was made from these tables. The test set was scored once, with the final model.",
             "Validation: `val_unseen_basins` = station folds 0 and 1 of `splits.json` (96 training basins held out,",
             "model fitted on the other 143); `val_temporal` = all 239 training basins, fit to 2006-09, validate",
             "2006-10 to 2008-09 (persistence and LightGBM use the same splits). Generated by",
             "`scripts/summarize_validation.py`.", "", "## Experiments", "",
             "| run | what it tests |", "|---|---|"]
    lines += [f"| {label} (`{run}`) | {what} |" for run, label, what in RUNS if (OUT / run).exists()]
    for ts, title in (("val_unseen_basins", "Unseen basins (headline)"), ("val_temporal", "Later years")):
        lines += ["", f"## {title}: `{ts}`", ""] + table(ts) + ["", "Intervals (target coverage 0.80):", ""] \
            + interval_table(ts)
    lines += ["", "## Robustness (H4): validation stress tests, `val_temporal`", "",
              "Same scenarios as the test-set stress tests: inputs removed at random (10%, 30%), 3-7 day gaps,",
              "weather noise, latest flow observation 1 day late.", ""] + stress_table()
    lines += ["", "## Decisions", "",
              "1. **LightGBM over persistence:** better on every horizon for NSE, MAE, AUPRC, Brier skill, with "
              "calibrated and narrower ranges at 3 and 7 days.",
              "2. **Mean forecast (v2) over median (v1):** higher NSE and KGE at every horizon; MAE slightly higher "
              "(expected: the median minimises absolute error). NSE is the primary skill metric.",
              "3. **H1 (catchment attributes):** small, consistent gains in most metrics, within the confidence "
              "intervals. Kept. Most transfer comes from predicting change relative to the basin's own flow.",
              "4. **H4 (robustness training):** rule fixed before looking: adopt if mean stressed 1-day NSE improves "
              "by >= 0.01 and clean unseen-basin NSE drops by < 0.02. Result: +0.025 and -0.011, so adopted.",
              "5. **Final combination (H4 + mean):** kept if its unseen-basin 1-day NSE is within 0.02 of v2.",
              "6. **No flow history:** not a candidate; reported as the ungauged-basin case.", ""]
    Path("docs/EXPERIMENTS.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()

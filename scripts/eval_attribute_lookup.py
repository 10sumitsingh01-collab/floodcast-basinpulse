"""Does looking up real catchment attributes help on rivers the model never saw?

    python scripts/eval_attribute_lookup.py

An uploaded file (website, or predict.py without --static) usually has no catchment attributes. Before, they were
left empty (only climate indices were computed from the file's weather); now predict.py fills them from
models/catchment_attributes.parquet when the gauge is known. This compares both on 80 Central European (LaMAH-CE)
rivers drawn at random (seed 1). The submitted model was trained on US rivers only, so all 80 are unseen.
Inputs 2008-10 to 2013-12; scored from 2010 on (flow) and against the official 1981-2008 flood lines (events).
Writes docs/ATTRIBUTE_LOOKUP.md.
"""
from __future__ import annotations

import sys
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, brier_score_loss

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import predict as P  # noqa: E402

DATA = ROOT / "data" / "transfer_lamah"
HS = (1, 3, 7)


def nse(y: pd.Series, f: pd.Series) -> float:
    ok = y.notna() & f.notna()
    y, f = y[ok], f[ok]
    return float(1 - ((f - y) ** 2).sum() / ((y - y.mean()) ** 2).sum())


def main() -> int:
    m = joblib.load(ROOT / "models" / "basinpulse_final.joblib")
    t = pd.read_parquet(DATA / "test.parquet")
    lab = pd.read_parquet(DATA / "test_labels.parquet")
    thr_ref = pd.read_csv(DATA / "thresholds.csv", dtype={P.ID: str})
    ids = sorted(np.random.default_rng(1).choice(sorted(t[P.ID].unique()), 80, replace=False))
    rows = P.continuous(t[t[P.ID].isin(ids) & (t[P.DATE] >= "2008-10-01") & (t[P.DATE] <= "2013-12-31")]
                        [[P.ID, P.DATE, P.OBS] + P.WEATHER])
    thr = P.derive_thresholds(rows, thr_ref)
    res, per = {}, {}
    for look in (False, True):
        pr = m.predict(m, rows, rows.iloc[:0], P.derive_static(rows, None, lookup=look), thr)
        d = pr[pr[P.DATE] >= "2010-01-01"].merge(lab, on=[P.ID, P.DATE]).merge(thr_ref[[P.ID, "q_high"]], on=P.ID)
        r, b = {}, {}
        for h in HS:
            x = d[d.horizon == h].dropna(subset=[f"streamflow_h{h}"])
            y, ev = x[f"streamflow_h{h}"], x[f"streamflow_h{h}"] > x.q_high
            b[h] = pd.Series({g: nse(gx[f"streamflow_h{h}"], gx.predicted_discharge) for g, gx in x.groupby(P.ID)})
            r[h] = {"NSE, median over rivers": b[h].median(), "High-flow AUPRC": average_precision_score(ev, x.p_high),
                    "Brier score, high flow (lower is better)": brier_score_loss(ev, x.p_high),
                    "10–90% range coverage (target 0.80)": ((y >= x.lower) & (y <= x.upper)).mean(),
                    "high-flow days": int(ev.sum())}
        res[look], per[look] = r, b
        print(f"lookup={look}: done", flush=True)

    L = ["# Catchment-attribute lookup: effect on unseen rivers", "",
         "Generated by `scripts/eval_attribute_lookup.py`. 80 Central European rivers (LaMAH-CE, random draw, seed 1), "
         "never seen by the submitted model (trained on US rivers only). Same inputs, same model; the only difference "
         "is whether missing catchment attributes are filled from `models/catchment_attributes.parquet`.", "",
         "| | 1 day | 3 days | 7 days |", "|---|---|---|---|"]
    for k in res[False][1]:
        if k == "high-flow days":
            continue
        L.append(f"| {k}: without → **with** lookup | " + " | ".join(
            f"{res[False][h][k]:.3f} → **{res[True][h][k]:.3f}**" for h in HS) + " |")
    rng = np.random.default_rng(0)
    cells = []
    for h in HS:
        dd = (per[True][h] - per[False][h]).dropna()
        bs = rng.choice(dd.values, (2000, len(dd))).mean(1)
        cells.append(f"{dd.mean():+.3f} [{np.percentile(bs, 2.5):+.3f}, {np.percentile(bs, 97.5):+.3f}], "
                     f"better on {int((dd > 0).sum())}/{len(dd)}")
    L.append("| Per-river NSE change: mean [95% CI], rivers better | " + " | ".join(cells) + " |")
    L.append(f"| High-flow days scored | " + " | ".join(f"{res[True][h]['high-flow days']:,}" for h in HS) + " |")
    L += ["", "**Reading.** With real attributes the flood probabilities are better at every horizon (higher AUPRC, "
          "lower Brier score) and the 10–90% range moves from too wide to close to the 80% target. Flow forecasts improve "
          "too: the median over rivers rises at every horizon and most rivers get better, with the largest gains "
          "on rivers whose guessed attributes were far off. Adopted as the default in "
          "`predict.py` and on the website; `--no-attribute-lookup` turns it off, and a user's own attribute file "
          "always takes precedence."]
    (ROOT / "docs" / "ATTRIBUTE_LOOKUP.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""Early-warning lead time and regional skill (BASINSHIFT 10.1 event detection, 10.4 "by region").

    python scripts/warning_and_regions.py --runs outputs/lgbm_final outputs/persistence_baseline outputs/climatology_baseline

Lead time: a flood onset is the first day flow exceeds the basin's 95th-percentile threshold after a day below it.
The onset on day D counts as warned h days ahead if the forecast issued at the end of day D-h, for horizon h,
gave P(high flow) >= 0.5. We report the share of onsets warned >= 1, >= 3 and >= 7 days ahead.
Regions: USGS hydrologic "parts" (first two digits of the gauge number). Scoring code: reads test labels.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src import evaluate  # noqa: E402

ID, DATE = "gauge_id", "date"
REGIONS = {
    "01": "New England", "02": "Mid- & South Atlantic", "03": "Ohio", "04": "Great Lakes",
    "05": "Upper Mississippi", "06": "Missouri", "07": "Lower Mississippi", "08": "Western Gulf (Texas)",
    "09": "Colorado", "10": "Great Basin", "11": "California", "12": "Pacific NW (Washington)",
    "13": "Snake", "14": "Pacific NW (Oregon)",
}


def region(gid: str) -> str:
    return gid.split("_", 1)[-1][:2]


def onsets(labels: pd.DataFrame, thr: pd.DataFrame) -> pd.DataFrame:
    """Flood onsets from observed flow. streamflow_h1 at origin t is the flow on day t+1."""
    obs = labels[[ID, DATE, "test_set", "streamflow_h1"]].copy()
    obs[DATE] = obs[DATE] + pd.Timedelta(days=1)
    obs = obs.rename(columns={"streamflow_h1": "q"}).merge(thr[[ID, "q_high"]], on=ID)
    obs = obs.sort_values([ID, DATE]).reset_index(drop=True)
    above = obs["q"] > obs["q_high"]
    prev = above.groupby(obs[ID]).shift(1, fill_value=False)
    prev_date_ok = obs[DATE].diff().dt.days.eq(1) & obs[ID].eq(obs[ID].shift())
    onset = above & ~prev & prev_date_ok & obs["q"].notna()
    return obs.loc[onset, [ID, DATE, "test_set"]].rename(columns={DATE: "onset"})


THRESHOLDS = (0.5, 0.3, 0.2)   # fixed operating points, reported side by side (not chosen on test results)


def lead_times(preds: pd.DataFrame, ev: pd.DataFrame, level: float) -> pd.DataFrame:
    out = ev.copy()
    p = preds[[ID, DATE, "horizon", "p_high"]]
    for h in (1, 3, 7):
        q = out[[ID, "onset"]].assign(**{DATE: out["onset"] - pd.Timedelta(days=h), "horizon": h})
        m = q.merge(p, on=[ID, DATE, "horizon"], how="left")
        out[f"warned_{h}"] = (m["p_high"] >= level).to_numpy()
        out[f"has_{h}"] = m["p_high"].notna().to_numpy()
    out["lead"] = np.select([out.warned_7, out.warned_3, out.warned_1], [7, 3, 1], default=0)
    return out


def false_alarms(preds: pd.DataFrame, labels: pd.DataFrame, thr: pd.DataFrame, ts: str, level: float) -> float:
    """1-day alerts (p_high >= level) on days that were not high-flow days, per basin-year."""
    j = evaluate.join(preds[preds.horizon == 1], labels[labels.test_set == ts], thr)
    fa = ((j["p_high"] >= level) & ~j["ev_high"]).sum()
    return float(fa / (len(j) / 365.25))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--runs", type=Path, nargs="+", required=True, help="first run = the model; others = baselines")
    ap.add_argument("--data", type=Path, default=Path("data/caravan"))
    ap.add_argument("--out", type=Path, default=Path("docs/WARNING_AND_REGIONS.md"))
    a = ap.parse_args()
    labels = pd.read_parquet(a.data / "test_labels.parquet")
    thr = pd.read_csv(a.data / "thresholds.csv", dtype={ID: str})
    ev = onsets(labels, thr)
    # an onset belongs to a test set if all three forecast origins exist in that set
    lines = ["# Early-warning lead time and regional skill", "",
             "Generated by `scripts/warning_and_regions.py` from the final test predictions.", "",
             "## Early-warning lead time", "",
             "A flood onset = first day above the basin's 95th-percentile flow. *Warned h days ahead* = the forecast "
             "issued h days before the onset gave P(high flow) >= 0.5 for that day.", ""]
    for ts in ("geo_temporal", "temporal"):
        e = ev[ev.test_set == ts]
        lines += [f"### `{ts}`", "",
                  "| model | alert when P(high) >= | onsets warned >= 1 day ahead | >= 3 days | >= 7 days | "
                  "1-day false alarms per basin-year |", "|---|---|---|---|---|---|"]
        for run in a.runs:
            preds = pd.read_parquet(run / "predictions.parquet", columns=[ID, DATE, "horizon", "p_high"])
            for level in THRESHOLDS:
                lt = lead_times(preds, e, level)
                lt = lt[lt.has_1 & lt.has_3 & lt.has_7]
                n = len(lt)
                cells = [f"{(lt.lead >= k).mean():.0%}" for k in (1, 3, 7)]
                fa = false_alarms(preds, labels, thr, ts, level)
                lines.append(f"| {run.name} | {level} | " + " | ".join(cells) + f" | {fa:.1f} |")
        lines += [f"({n:,} flood onsets with all three forecast origins in the test set)", ""]

    model = a.runs[0]
    preds = pd.read_parquet(model / "predictions.parquet")
    base = a.runs[1] if len(a.runs) > 1 else None
    lines += ["## Skill by region", "",
              f"Median per-basin NSE of `{model.name}` (persistence in brackets), 3-day horizon.", "",
              "| region | basins seen (temporal) | NSE 3d, seen basins | basins unseen (geo_temporal) | NSE 3d, unseen basins |",
              "|---|---|---|---|---|"]
    tables = {}
    for run in [model] + ([base] if base else []):
        p = pd.read_parquet(run / "predictions.parquet")
        j = evaluate.join(p, labels, thr)
        j = j[j.horizon == 3]
        res = {}
        for ts in ("temporal", "geo_temporal"):
            bm = evaluate.basin_metrics(j[j.test_set == ts])
            bm["region"] = [region(g) for g in bm.index]
            res[ts] = bm.groupby("region")["nse"].agg(["median", "size"])
        tables[run.name] = res
    m, b = tables[model.name], tables.get(base.name) if base else None
    for r in sorted(REGIONS):
        cells = []
        for ts in ("temporal", "geo_temporal"):
            if r in m[ts].index:
                v = m[ts].loc[r]
                bv = f" ({b[ts].loc[r, 'median']:.2f})" if b is not None and r in b[ts].index else ""
                cells += [f"{int(v['size'])}", f"{v['median']:.2f}{bv}"]
            else:
                cells += ["0", "n/a"]
        lines.append(f"| {r} {REGIONS[r]} | " + " | ".join(cells) + " |")
    lines += ["", "Small regions (< 5 unseen basins) give noisy medians; read them as indications, not rankings.", ""]
    a.out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()

"""Split summary (BASINSHIFT 7.3): are the held-out basins representative of the training basins?

    python scripts/caravan/split_summary.py --data data/caravan --out docs

Writes docs/SPLIT_SUMMARY.md (distribution of catchment characteristics per split) and
docs/basin_map.png (basin locations coloured by split). Uses train.parquet, test.parquet, static.parquet
and thresholds.csv only; no test labels.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

ID, DATE = "gauge_id", "date"
ATTRS = [
    ("area_km2", "Area (km²)", "{:,.0f}"),
    ("aridity", "Aridity (PET/P)", "{:.2f}"),
    ("p_mean", "Mean precipitation (mm/day)", "{:.2f}"),
    ("frac_snow", "Snow fraction of precipitation", "{:.2f}"),
    ("high_prec_freq", "High-precipitation day frequency", "{:.3f}"),
    ("ele_mt_sav", "Mean elevation (m)", "{:,.0f}"),
    ("slp_dg_sav", "Mean slope (0.1°)", "{:.0f}"),
    ("for_pc_sse", "Forest cover (%)", "{:.0f}"),
    ("dor_pc_pva", "Degree of regulation (%)", "{:.1f}"),
    ("q_high", "High-flow threshold q95 (mm/day)", "{:.2f}"),
]


def region_of(gid: str) -> str:
    num = gid.split("_", 1)[-1]
    return num[:2] if num[:2].isdigit() else "other"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data", type=Path, default=Path("data/caravan"))
    ap.add_argument("--out", type=Path, default=Path("docs"))
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)

    static = pd.read_parquet(a.data / "static.parquet")
    thr = pd.read_csv(a.data / "thresholds.csv", dtype={ID: str})
    train_ids = set(pd.read_parquet(a.data / "train.parquet", columns=[ID])[ID])
    tr = pd.read_parquet(a.data / "train.parquet", columns=[ID, "streamflow"])
    rec_years = tr.dropna().groupby(ID).size() / 365.25

    s = static.merge(thr[[ID, "q_high"]], on=ID)
    s["split"] = np.where(s[ID].isin(train_ids), "train (239)", "held out (60)")
    s["region"] = s[ID].map(region_of)
    s["record_years"] = s[ID].map(rec_years)

    rows = []
    for col, label, fmt in ATTRS:
        cells = []
        for sp in ("train (239)", "held out (60)"):
            v = s.loc[s.split == sp, col]
            cells.append(f"{fmt.format(v.median())} ({fmt.format(v.quantile(0.1))} – {fmt.format(v.quantile(0.9))})")
        a_tr, a_ho = s.loc[s.split == "train (239)", col], s.loc[s.split == "held out (60)", col]
        # Kolmogorov-Smirnov statistic: 0 = identical distributions
        grid = np.sort(np.concatenate([a_tr, a_ho]))
        ks = np.max(np.abs(np.searchsorted(np.sort(a_tr), grid, "right") / len(a_tr)
                           - np.searchsorted(np.sort(a_ho), grid, "right") / len(a_ho)))
        rows.append(f"| {label} | {cells[0]} | {cells[1]} | {ks:.2f} |")

    reg = s.groupby(["region", "split"]).size().unstack(fill_value=0)
    reg_rows = [f"| {r} | {int(x.get('train (239)', 0))} | {int(x.get('held out (60)', 0))} |" for r, x in reg.iterrows()]

    md = f"""# Split summary (BASINSHIFT 7.3)

Generated by `scripts/caravan/split_summary.py`. 299 CAMELS-US basins: 239 used for training, 60 held out
entirely (no training rows), sampled in proportion to 14 USGS regions.

## Catchment characteristics: median (10th – 90th percentile)
The KS column is the Kolmogorov-Smirnov distance between the two distributions (0 = identical; with
60 vs 239 basins, values below ~0.2 are consistent with the same distribution).

| Characteristic | Train basins | Held-out basins | KS |
|---|---|---|---|
{chr(10).join(rows)}

Training record per train basin: median {rec_years.median():.1f} years of observed flow (1981-10 to 2008-09).

## Basins per USGS region (first two digits of the gauge number)
| Region | Train | Held out |
|---|---|---|
{chr(10).join(reg_rows)}

Map: ![basin map](basin_map.png)
"""
    (a.out / "SPLIT_SUMMARY.md").write_text(md, encoding="utf-8")

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(10, 5.6), dpi=150)
    for sp, color, size, marker in (("train (239)", "#4C78A8", 22, "o"), ("held out (60)", "#E45756", 46, "^")):
        d = s[s.split == sp]
        ax.scatter(d.gauge_lon, d.gauge_lat, s=size, c=color, marker=marker, label=f"{sp} basins",
                   edgecolors="white", linewidths=0.5, alpha=0.9)
    ax.set_xlabel("Longitude")
    ax.set_ylabel("Latitude")
    ax.set_title("BasinPulse: CAMELS-US basins by split (held-out basins are never used in training)")
    ax.set_aspect(1.25)
    ax.grid(alpha=0.25)
    ax.legend(loc="lower left", frameon=True)
    fig.tight_layout()
    fig.savefig(a.out / "basin_map.png")
    print(md)


if __name__ == "__main__":
    main()

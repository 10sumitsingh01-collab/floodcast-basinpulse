"""Where does the model fail? Per-basin skill on unseen basins vs catchment characteristics (BASINSHIFT 10.4, 12.2 Q7).

    python scripts/failure_analysis.py --run outputs/lgbm_final --baseline outputs/persistence_baseline

Writes docs/FAILURE_ANALYSIS.md from a finished run (scoring code only; reads test labels like evaluate.py).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src import evaluate  # noqa: E402

ID = "gauge_id"
CHARS = [("aridity", "aridity (PET/P)"), ("frac_snow", "snow fraction"), ("area_km2", "area (km²)"),
         ("slp_dg_sav", "slope"), ("high_prec_freq", "high-precipitation frequency"),
         ("dor_pc_pva", "degree of regulation"), ("for_pc_sse", "forest cover"), ("ele_mt_sav", "elevation")]


def per_basin(run: Path, data: Path, test_set: str) -> pd.DataFrame:
    preds = pd.read_parquet(run / "predictions.parquet")
    labels = pd.read_parquet(data / "test_labels.parquet")
    thr = pd.read_csv(data / "thresholds.csv", dtype={ID: str})
    j = evaluate.join(preds, labels[labels.test_set == test_set], thr)
    out = []
    for h, g in j.groupby("horizon"):
        bm = evaluate.basin_metrics(g)[["nse", "kge", "mae"]].add_suffix(f"_h{h}")
        out.append(bm)
    return pd.concat(out, axis=1)


def spearman(a: pd.Series, b: pd.Series) -> float:
    ok = a.notna() & b.notna()
    return float(a[ok].rank().corr(b[ok].rank()))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run", type=Path, required=True)
    ap.add_argument("--baseline", type=Path, default=Path("outputs/persistence_baseline"))
    ap.add_argument("--data", type=Path, default=Path("data/caravan"))
    ap.add_argument("--out", type=Path, default=Path("docs/FAILURE_ANALYSIS.md"))
    ap.add_argument("--test-set", default="geo_temporal")
    a = ap.parse_args()

    st = pd.read_parquet(a.data / "static.parquet").set_index(ID)
    m = per_basin(a.run, a.data, a.test_set)
    b = per_basin(a.baseline, a.data, a.test_set)
    df = m.join(st[[c for c, _ in CHARS]])
    df["gain_nse_h3"] = m["nse_h3"] - b["nse_h3"]

    lines = [f"# Failure analysis: `{a.run.name}` on `{a.test_set}` ({len(df)} basins never used in training)", "",
             "Per-basin NSE (median over basins is the headline metric). Generated by `scripts/failure_analysis.py`.", ""]
    q = df[["nse_h1", "nse_h3", "nse_h7"]].describe(percentiles=[0.1, 0.25, 0.5, 0.75, 0.9]).T
    lines += ["## Spread of per-basin NSE", "", "| horizon | 10% | 25% | median | 75% | 90% | basins with NSE < 0 |",
              "|---|---|---|---|---|---|---|"]
    for h in (1, 3, 7):
        r = q.loc[f"nse_h{h}"]
        neg = int((df[f"nse_h{h}"] < 0).sum())
        lines.append(f"| {h} day | {r['10%']:.2f} | {r['25%']:.2f} | {r['50%']:.2f} | {r['75%']:.2f} | "
                     f"{r['90%']:.2f} | {neg} |")
    lines += ["", f"Model beats persistence (higher 3-day NSE) on {int((df.gain_nse_h3 > 0).sum())} of "
              f"{df.gain_nse_h3.notna().sum()} basins.", ""]

    lines += ["## Which catchments are hard? Spearman correlation of 3-day NSE with characteristics", "",
              "| characteristic | correlation | median NSE (lowest third) | median NSE (highest third) |",
              "|---|---|---|---|"]
    for c, label in CHARS:
        r = spearman(df["nse_h3"], df[c])
        terc = pd.qcut(df[c].rank(method="first"), 3, labels=False)
        lo, hi = df.loc[terc == 0, "nse_h3"].median(), df.loc[terc == 2, "nse_h3"].median()
        lines.append(f"| {label} | {r:+.2f} | {lo:.2f} | {hi:.2f} |")

    worst = df.sort_values("nse_h3").head(8)
    lines += ["", "## Worst basins (3-day NSE)", "",
              "| basin | NSE 1d | NSE 3d | NSE 7d | aridity | snow | area km² | slope |", "|---|---|---|---|---|---|---|---|"]
    for gid, r in worst.iterrows():
        lines.append(f"| {gid} | {r.nse_h1:.2f} | {r.nse_h3:.2f} | {r.nse_h7:.2f} | {r.aridity:.2f} | "
                     f"{r.frac_snow:.2f} | {r.area_km2:,.0f} | {r.slp_dg_sav:.0f} |")
    lines.append("")
    a.out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
